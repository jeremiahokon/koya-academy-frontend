'use server';

import fs from 'node:fs/promises';
import path from 'node:path';

import { sanitizeClassName, validateSVG } from './utils';

export async function saveIcon(formData: FormData) {
  const svg = formData.get('svg') as string;
  const className = formData.get('className') as string;
  const displayType = formData.get('displayType') as string;
  const fileName = formData.get('fileName') as string;

  if (!svg || !className || !displayType || !fileName) {
    return { success: false, message: 'Missing required fields' };
  }

  // Validate SVG
  if (!validateSVG(svg)) {
    return { success: false, message: 'Invalid SVG format' };
  }

  // Sanitize class name
  const sanitizedClassName = sanitizeClassName(className);

  if (!sanitizedClassName) {
    return { success: false, message: 'Invalid class name' };
  }

  const publicDir = path.join(process.cwd(), 'public');
  const cssFilePath = path.join(publicDir, fileName);

  try {
    // Check if class name already exists
    const fileExists = await fs
      .access(cssFilePath)
      .then(() => true)
      .catch(() => false);

    if (fileExists) {
      const existingContent = await fs.readFile(cssFilePath, 'utf-8');

      if (existingContent.includes(`.${sanitizedClassName} {`)) {
        return {
          success: false,
          message: `Class name "${sanitizedClassName}" already exists`,
        };
      }
    }

    // Generate CSS content with consistent formatting
    const cssContent =
      displayType === 'background'
        ? `
/* ${sanitizedClassName} - Background Image */
.${sanitizedClassName} {
  background-image: url("data:image/svg+xml,${encodeURIComponent(svg)}");
  background-repeat: no-repeat;
  background-position: center;
  background-size: contain;
}

`
        : `
/* ${sanitizedClassName} - SVG Mask */
.${sanitizedClassName} {
  --svg: url("data:image/svg+xml,${encodeURIComponent(svg)}");
  display: inline-block;
  background-color: currentColor;
  -webkit-mask-image: var(--svg);
  mask-image: var(--svg);
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-size: 100% 100%;
  mask-size: 100% 100%;
}

`;

    await fs.appendFile(cssFilePath, cssContent);

    return {
      success: true,
      message: 'Icon saved successfully!',
      className: sanitizedClassName,
    };
  } catch (error) {
    console.error('Error saving icon:', error);

    return { success: false, message: 'Failed to save icon' };
  }
}

export async function createCssFile(fileName: string) {
  // Sanitize filename
  let sanitizedFileName = fileName
    .toLowerCase()
    .trim()
    .replace(/[_\s]+/g, '-')
    .replace(/[^a-z0-9-]/g, '');

  if (!sanitizedFileName.endsWith('.css')) {
    sanitizedFileName += '.css';
  }

  const publicDir = path.join(process.cwd(), 'public');
  const filePath = path.join(publicDir, sanitizedFileName);

  try {
    // Check if file already exists
    const fileExists = await fs
      .access(filePath)
      .then(() => true)
      .catch(() => false);

    if (fileExists) {
      return { success: false, message: 'CSS file already exists' };
    }

    const initialContent = `/* Custom Icons - ${sanitizedFileName} */
/* Generated by Dokita Icon Creator */
/* Usage: <i className="icon-{name}"></i> */

`;

    await fs.writeFile(filePath, initialContent);

    return {
      success: true,
      message: 'CSS file created successfully!',
      fileName: sanitizedFileName,
    };
  } catch (error) {
    console.error('Error creating CSS file:', error);

    return { success: false, message: 'Failed to create CSS file' };
  }
}

export async function getCssFiles() {
  const publicDir = path.join(process.cwd(), 'public');

  try {
    const files = await fs.readdir(publicDir);
    const cssFiles = files.filter((file) => file.endsWith('.css'));

    // Ensure custom-icons.css exists and is first
    if (!cssFiles.includes('custom-icons.css')) {
      await createCssFile('custom-icons');

      return ['custom-icons.css', ...cssFiles];
    }

    // Sort with custom-icons.css first
    return cssFiles.sort((a, b) => {
      if (a === 'custom-icons.css') return -1;
      if (b === 'custom-icons.css') return 1;

      return a.localeCompare(b);
    });
  } catch (error) {
    console.error('Error reading CSS files:', error);

    return [];
  }
}

export async function deleteIcon(formData: FormData) {
  const className = formData.get('className') as string;
  const fileName = formData.get('fileName') as string;

  if (!className || !fileName) {
    return { success: false, message: 'Missing required fields' };
  }

  const publicDir = path.join(process.cwd(), 'public');
  const cssFilePath = path.join(publicDir, fileName);

  try {
    const content = await fs.readFile(cssFilePath, 'utf-8');

    // Find and remove the icon's CSS block (including comment)
    const iconPattern = new RegExp(
      `\\/\\* ${className}[^*]*\\*\\/\\s*\\.${className}\\s*{[^}]*}\\s*`,
      'g'
    );

    const updatedContent = content.replace(iconPattern, '');

    await fs.writeFile(cssFilePath, updatedContent);

    return { success: true, message: 'Icon deleted successfully!' };
  } catch (error) {
    console.error('Error deleting icon:', error);

    return { success: false, message: 'Failed to delete icon' };
  }
}
